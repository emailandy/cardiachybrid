import sys
import csv
import io
import re
from collections import defaultdict
from pathlib import Path
from codegen.branching import compile_predicate
from codegen.redcap_dict_to_code import load_dictionary
import codegen.known_bugs as known_bugs

def main():
    dict_path = Path("dictionary/instrument.csv")
    specs = load_dictionary(dict_path)
    
    if hasattr(known_bugs, "BRANCHING_OVERRIDES"):
        for k in known_bugs.BRANCHING_OVERRIDES:
            print(f"WARNING: Staged branching override for '{k}' will not be applied (APPLY_OVERRIDES={known_bugs.APPLY_OVERRIDES}).")

    raw = dict_path.read_bytes().decode("utf-8-sig")
    try:
        dialect = csv.Sniffer().sniff(raw[:8192], delimiters=",\t")
    except csv.Error:
        dialect = csv.excel
        
    rdr = csv.DictReader(io.StringIO(raw), dialect=dialect)
    if not rdr.fieldnames or len(rdr.fieldnames) < 10:
        rdr = csv.DictReader(io.StringIO(raw), dialect=csv.excel)
        
    def slugify(text: str) -> str:
        return re.sub(r"[^a-z0-9]", "", text.lower())
        
    slug_to_header = {slugify(h): h for h in rdr.fieldnames}
    bl_slug = "branchinglogicshowfieldonlyif"
    bl_header = slug_to_header.get(bl_slug)
    name_header = slug_to_header.get("variablefieldname") or slug_to_header.get("field_name") or slug_to_header.get("variablename")

    unknown_refs = defaultdict(list)
    compiled_count = 0
    ref_re = re.compile(r"\[([a-zA-Z_][a-zA-Z0-9_]*)(?:\([^)]+\))?\]")

    out_lines = [
        "# generated/branching_compiled.py",
        "# DO NOT EDIT - Generated by codegen/emit_branching.py",
        "from typing import Callable, Dict, Any",
        "from codegen.branching import _v, _cb, _cmp, _truthy",
        "",
        "PREDICATES: Dict[str, Callable[[Dict[str, str]], bool]] = {}"
    ]

    for row in rdr:
        name = row[name_header]
        if not name: continue
        logic = row[bl_header].strip()
        if not logic: continue
        
        for m in ref_re.finditer(logic):
            ref = m.group(1).lower()
            if ref not in specs:
                unknown_refs[ref].append(name)
                
        try:
            pred = compile_predicate(logic)
            compiled_count += 1
            out_lines.append(f"\n# {name}: {logic}")
            out_lines.append(f"def _pred_{name}(record: Dict[str, str]) -> bool:")
            out_lines.append(f"    return bool(_truthy( {pred.source} ))")
            out_lines.append(f"PREDICATES[{name!r}] = _pred_{name}")
        except Exception as e:
            print(f"FAILED TO COMPILE: {name} | {logic} | {e}")
            raise

    for ref, users in unknown_refs.items():
        print(f"WARNING: Unknown field {ref!r} referenced in branching logic of {', '.join(users)}")
        
    out_path = Path("generated/branching_compiled.py")
    out_path.parent.mkdir(exist_ok=True)
    out_path.write_text("\n".join(out_lines) + "\n")

if __name__ == "__main__":
    main()
